#!/bin/sh
# Creates the firmware release signing key (ECDSA P-256) and the public-key header compiled into
# the firmware (firmware/paperbot/ota_pubkey.h).
#
#   sh tools/ota/keygen.sh            # once; refuses to overwrite an existing key
#   sh tools/ota/keygen.sh --header   # only regenerate ota_pubkey.h from the existing key
#
# The private key (default .secrets/ota_signing_key.pem, override with PV_OTA_KEY) never goes into
# git or the firmware. Back it up: devices only accept releases signed with the key whose public
# half they were built with; losing it means re-flashing every device over USB with a new key.
set -e
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
KEY=${PV_OTA_KEY:-$ROOT/.secrets/ota_signing_key.pem}
HDR=$ROOT/firmware/paperbot/ota_pubkey.h
if [ "$1" != "--header" ]; then
  if [ -e "$KEY" ]; then echo "keygen: $KEY exists - not overwriting (use --header to rewrite the header)" >&2; exit 1; fi
  mkdir -p "$(dirname "$KEY")"
  (umask 077 && openssl ecparam -name prime256v1 -genkey -noout -out "$KEY")
  echo "keygen: new signing key $KEY (back it up somewhere safe)"
fi
[ -r "$KEY" ] || { echo "keygen: no key at $KEY" >&2; exit 1; }
FP=$(openssl ec -in "$KEY" -pubout -outform DER 2>/dev/null | openssl dgst -sha256 | sed 's/.*= //' | cut -c1-16)
{
  echo "// Firmware release public key (ECDSA P-256, DER SubjectPublicKeyInfo), fingerprint $FP."
  echo "// Generated by tools/ota/keygen.sh. Only images whose manifest is signed with the matching"
  echo "// private key are installed over the air (pv_ota.h, docs/device-api.md section 6)."
  echo "#pragma once"
  echo "#define PV_OTA_KEY_FINGERPRINT \"$FP\""
  echo "static const unsigned char PV_OTA_PUBKEY_DER[] = {"
  openssl ec -in "$KEY" -pubout -outform DER 2>/dev/null | xxd -i
  echo "};"
} > "$HDR"
echo "keygen: wrote $HDR (fingerprint $FP)"
